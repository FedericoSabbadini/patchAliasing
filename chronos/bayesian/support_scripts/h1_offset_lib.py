def _cfg(config: H1OffsetConfig | None) -> H1OffsetConfig:
    return config if config is not None else H1OffsetConfig()


def _model_tag(model: tuple[int, int]) -> str:
    return pl.model_tag(int(model[0]), int(model[1]))


def _normalise_models(models: Sequence[tuple[int, int]]) -> tuple[tuple[int, int], ...]:
    out = tuple((int(P), int(S)) for P, S in models)
    if not out:
        raise ValueError("models cannot be empty")
    if len(set(out)) != len(out):
        raise ValueError("models contains duplicates")
    unknown = [m for m in out if m not in FROZEN_BAYES_MODELS]
    if unknown:
        raise ValueError(f"models outside FROZEN_BAYES_MODELS: {unknown}")
    return out


def _config_payload(config: H1OffsetConfig) -> dict[str, object]:
    payload = asdict(config)
    payload["generators"] = list(config.generators)
    return payload


def _config_fingerprint(config: H1OffsetConfig) -> str:
    raw = json.dumps(_config_payload(config), sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def _file_sha256(path: Path) -> str:
    """Return a streaming content digest for provenance-sensitive source files."""

    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _directory_sha256(root: Path) -> str:
    """Hash names and contents of a resolved local checkpoint directory."""

    digest = hashlib.sha256()
    files = sorted(path for path in root.rglob("*") if path.is_file())
    if not files:
        raise ValueError(f"local checkpoint directory is empty: {root}")
    for path in files:
        relative = path.relative_to(root).as_posix().encode("utf-8")
        digest.update(len(relative).to_bytes(8, "big"))
        digest.update(relative)
        digest.update(path.stat().st_size.to_bytes(8, "big"))
        with path.open("rb") as handle:
            for block in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(block)
    return digest.hexdigest()


def _source_provenance() -> dict[str, dict[str, str]]:
    """Source identities that must match before an old collection can resume."""

    paths = {
        "h1_offset_lib": Path(__file__).resolve(),
        "probe_lib": Path(pl.__file__).resolve(),
    }
    return {
        name: {"file": path.name, "sha256": _file_sha256(path)}
        for name, path in paths.items()
    }


