@dataclass(frozen=True)
class H1OffsetConfig:
    """Complete design configuration for the paired H1 offset experiment."""

    fixed_offset_hz: float = 1.0
    guard_hz: float = 1.0
    adaptive_step_hz: float = 0.05
    n_phase: int = 10
    n_bg: int = 100
    generators: tuple[str, ...] = pl.GENERATORS
    batch_size: int = 64
    device: str | None = None
    seed: int = 42
    background_seed0: int = 10_000
    epsilon: float = 0.01
    live_threshold: float = 0.05
    smoke: bool = False

    def __post_init__(self) -> None:
        if self.fixed_offset_hz <= 0:
            raise ValueError("fixed_offset_hz must be positive")
        if self.guard_hz < 0:
            raise ValueError("guard_hz cannot be negative")
        if self.adaptive_step_hz <= 0:
            raise ValueError("adaptive_step_hz must be positive")
        if self.n_phase < 1 or self.n_bg < 1 or self.batch_size < 1:
            raise ValueError("n_phase, n_bg and batch_size must be positive integers")
        if not self.generators:
            raise ValueError("at least one background generator is required")
        if len(set(self.generators)) != len(self.generators):
            raise ValueError("generators must be unique")
        if self.epsilon <= 0:
            raise ValueError("epsilon must be positive")
        if self.live_threshold < 0:
            raise ValueError("live_threshold cannot be negative")

    @classmethod
    def smoke_config(cls, **overrides: object) -> "H1OffsetConfig":
        """Return a tiny real-pipeline configuration whose outputs are non-reportable."""

        cfg = cls(
            n_phase=2,
            n_bg=1,
            generators=("tsmixup",),
            batch_size=32,
            smoke=True,
        )
        return replace(cfg, **overrides)


