"""Paired H1 collection for fixed and adaptive frequency controls.

This module is deliberately separate from :mod:`collect`: it supports the H1-only
offset sensitivity notebook without changing the data or checkpoints used by the
full Bayesian workflow.  Every observation contains both contrasts on the same
model, lock, background and phase.  The lock recovery is therefore evaluated once
and shared by the fixed- and adaptive-offset estimands.

Real collection writes one shard per geometry plus a JSON design manifest.  Smoke
data generated by :func:`synthetic_paired_data` never load Chronos and are marked
``reportable=False`` so they cannot be confused with empirical results.
"""

